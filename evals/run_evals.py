"""Eval harness: measure the TTS text-normalisation stage.

For every sample in ``samples.json`` this runs the real
``app.services.kokoro_service._normalize_numbers`` (the deterministic
TTS-prep stage that turns digits into spoken words) and reports:

* **Normalisation correctness** - exact match against ``gold.json``.
  The gold strings were written by hand from the spoken-form rules
  (years as year pairs in year contexts, ordinals, fractions, phone
  numbers read as number groups, ...). A mismatch is a harness
  failure and is reported, never edited away silently.
* **Processing latency** - wall-clock per normalisation call
  (mean of repeated runs, plus mean/p50/p95 across samples).
* **Cost per finished video** - a documented *model*, not a
  measurement: the normalisation stage is measured directly, the
  downstream TTS/render stages are estimated from the assumptions
  listed in RESULTS.md.

Scope boundary: the Kokoro TTS model itself is NOT executed here
(model weights are a local download, not a repo fixture), and no LLM
provider is called, so script-generation quality/cost is outside
this harness. Everything labelled "measured" below was produced by
this script on the machine that ran it; everything labelled
"estimate" comes from the stated assumptions.

Usage (from the repository root, in an environment with the backend
requirements installed):

    python -m evals.run_evals

Writes ``evals/RESULTS.md`` and exits non-zero if any sample misses
its gold expectation.
"""

import json
import statistics
import sys
import time
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
EVALS_DIR = Path(__file__).resolve().parent
BACKEND_DIR = REPO_ROOT / "backend"

REPEATS = 25  # timed repetitions per sample (after one warm-up call)

# --- Cost-model assumptions (estimates, NOT measurements) -------------------
# Narration pace used to turn spoken words into audio duration.
WORDS_PER_MINUTE = 150
# CPU synthesis cost per word: backend/app/core/config.py documents
# ~0.7-1.0 s/word for CPU synthesis; the model uses the midpoint.
TTS_SECONDS_PER_WORD = 0.85
# Assumed price of one CPU core-hour on a small cloud instance (USD).
CPU_CORE_HOUR_USD = 0.046


def _load_json(name):
    with open(EVALS_DIR / name, encoding="utf-8") as fh:
        return json.load(fh)


def _percentile(values, pct):
    ordered = sorted(values)
    rank = max(1, -(-pct * len(ordered) // 100))  # nearest-rank, ceil
    return ordered[min(rank, len(ordered)) - 1]


def run():
    if str(BACKEND_DIR) not in sys.path:
        sys.path.insert(0, str(BACKEND_DIR))
    # Imported here so --help-style usage errors surface before the
    # heavy backend import chain (torch/kokoro) is pulled in.
    from app.services.kokoro_service import _normalize_numbers

    samples = _load_json("samples.json")
    gold = _load_json("gold.json")

    rows = []
    for sample in samples:
        text = sample["text"]
        expected = gold[sample["id"]]

        _normalize_numbers(text)  # warm-up
        timings = []
        actual = None
        for _ in range(REPEATS):
            start = time.perf_counter()
            actual = _normalize_numbers(text)
            timings.append((time.perf_counter() - start) * 1000.0)

        spoken_words = len(actual.split())
        est_audio_min = spoken_words / WORDS_PER_MINUTE
        est_tts_s = spoken_words * TTS_SECONDS_PER_WORD
        est_cost_usd = est_tts_s / 3600.0 * CPU_CORE_HOUR_USD
        rows.append(
            {
                "id": sample["id"],
                "chars": len(text),
                "match": actual == expected,
                "actual": actual,
                "expected": expected,
                "mean_ms": statistics.mean(timings),
                "spoken_words": spoken_words,
                "est_audio_min": est_audio_min,
                "est_tts_s": est_tts_s,
                "est_cost_usd": est_cost_usd,
            }
        )

    matched = sum(1 for r in rows if r["match"])
    lat = [r["mean_ms"] for r in rows]
    summary = {
        "samples": len(rows),
        "matched": matched,
        "exact_match_pct": 100.0 * matched / len(rows),
        "lat_mean": statistics.mean(lat),
        "lat_p50": _percentile(lat, 50),
        "lat_p95": _percentile(lat, 95),
        "total_spoken_words": sum(r["spoken_words"] for r in rows),
        "total_audio_min": sum(r["est_audio_min"] for r in rows),
        "total_tts_s": sum(r["est_tts_s"] for r in rows),
        "total_cost_usd": sum(r["est_cost_usd"] for r in rows),
    }
    return rows, summary


def render_results(rows, summary):
    lines = []
    lines.append("# Eval results — TTS text normalisation")
    lines.append("")
    lines.append(f"_Generated by `python -m evals.run_evals` on {date.today().isoformat()}. "
                 "Regenerate after any normalisation change; do not hand-edit the numbers._")
    lines.append("")
    lines.append("## Method")
    lines.append("")
    lines.append("- **Stage under test:** `app.services.kokoro_service._normalize_numbers` — the "
                 "deterministic TTS-prep stage that converts digits to spoken words before synthesis.")
    lines.append(f"- **Samples:** {summary['samples']} fixed narration texts in `evals/samples.json`, "
                 "covering years in context vs bare quantities, ordinals, fractions, phone numbers, "
                 "money, decimals, percentages and times.")
    lines.append("- **Correctness:** exact match against `evals/gold.json`. Gold strings were written "
                 "by hand from the spoken-form rules and are the harness's expectations; a mismatch "
                 "fails the run (exit code 1) and is shown below, not hidden.")
    lines.append(f"- **Latency:** mean of {REPEATS} timed calls per sample after one warm-up call, "
                 "on the machine that ran the harness.")
    lines.append("- **Boundary:** the Kokoro TTS model itself is not executed by this harness (model "
                 "weights are a local download, not a repo fixture) and no LLM provider is called, so "
                 "synthesis quality and script-generation cost are out of scope. The cost column is a "
                 "model built from the assumptions below — it is an estimate, not a measurement.")
    lines.append("")
    lines.append("## Results")
    lines.append("")
    lines.append("| Sample | Chars | Gold match | Norm. latency (ms, mean) | Spoken words | Est. audio (min) | Est. TTS compute (s) | Est. cost/video (USD) |")
    lines.append("|---|---:|:---:|---:|---:|---:|---:|---:|")
    for r in rows:
        lines.append(
            f"| {r['id']} | {r['chars']} | {'PASS' if r['match'] else 'FAIL'} | "
            f"{r['mean_ms']:.3f} | {r['spoken_words']} | {r['est_audio_min']:.2f} | "
            f"{r['est_tts_s']:.1f} | {r['est_cost_usd']:.4f} |"
        )
    lines.append(
        f"| **All samples** | | **{summary['matched']}/{summary['samples']} "
        f"({summary['exact_match_pct']:.1f}%)** | mean {summary['lat_mean']:.3f} / "
        f"p50 {summary['lat_p50']:.3f} / p95 {summary['lat_p95']:.3f} | "
        f"{summary['total_spoken_words']} | {summary['total_audio_min']:.2f} | "
        f"{summary['total_tts_s']:.1f} | {summary['total_cost_usd']:.4f} |"
    )
    lines.append("")
    lines.append("## Cost-model assumptions (estimates, not measurements)")
    lines.append("")
    lines.append(f"- Narration pace: {WORDS_PER_MINUTE} words/minute of spoken output.")
    lines.append(f"- TTS compute: {TTS_SECONDS_PER_WORD} s of CPU per spoken word — the midpoint of the "
                 "0.7–1.0 s/word range documented for CPU synthesis in `backend/app/core/config.py`.")
    lines.append(f"- Compute price: ${CPU_CORE_HOUR_USD:.3f} per CPU core-hour (small cloud instance).")
    lines.append("- The normalisation stage itself is measured above (sub-millisecond to a few "
                 "milliseconds per script) and is negligible next to synthesis; rendering/encoding "
                 "and any LLM script generation are excluded.")
    lines.append("")

    failures = [r for r in rows if not r["match"]]
    if failures:
        lines.append("## Mismatches (gold expectation vs actual)")
        lines.append("")
        for r in failures:
            lines.append(f"### {r['id']}")
            lines.append("")
            lines.append(f"- Expected: {r['expected']}")
            lines.append(f"- Actual:   {r['actual']}")
            lines.append("")
    return "\n".join(lines)


def main():
    rows, summary = run()
    out = render_results(rows, summary)
    (EVALS_DIR / "RESULTS.md").write_text(out + "\n", encoding="utf-8")
    print(
        f"evals: {summary['matched']}/{summary['samples']} samples match gold "
        f"({summary['exact_match_pct']:.1f}%), latency mean "
        f"{summary['lat_mean']:.3f} ms / p95 {summary['lat_p95']:.3f} ms -> evals/RESULTS.md"
    )
    return 0 if summary["matched"] == summary["samples"] else 1


if __name__ == "__main__":
    sys.exit(main())
